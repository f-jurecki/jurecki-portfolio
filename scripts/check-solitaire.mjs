import assert from 'node:assert/strict';
import { cardFiles, deal, validState, rank, suit, canMove, move, autoMove, draw, won, canFinish, foundationMove, hints } from '../src/lib/solitaire.mjs';

assert.equal(new Set(cardFiles.flat()).size, 52);
assert.equal(cardFiles[0][12], 49);
assert.equal(cardFiles[1][0], 7);
for (let i = 0; i < 30; i++) {
	const state = deal();
	assert.ok(validState(state));
	assert.deepEqual(state.tableau.map((pile) => pile.length), [1, 2, 3, 4, 5, 6, 7]);
	assert.equal(state.stock.length, 24);
	const original = structuredClone(state);
	let next = state;
	for (let j = 0; j < 24; j++) next = draw(next);
	assert.deepEqual(draw(next).stock, state.stock, 'Recycling preserves draw order');
	assert.deepEqual(state, original, 'Drawing does not mutate the previous undo state');
	const suggestions = hints(state);
	for (let repeat = 0; repeat < 120; repeat++) assert.deepEqual(hints(state), suggestions, 'Hints remain unlimited');
	assert.deepEqual(state, original, 'Hints do not change the game or move counter');
	for (const hint of suggestions) assert.ok(hint.draw ? draw(state) : canMove(state, hint.from, hint.to), 'Every hint is legal');
}

const from = { zone: 'tableau', pile: 0, index: 0 };
const to = { zone: 'tableau', pile: 1 };
let state = deal();
state.tableau = [[{ id: 11, up: true }, { id: 23, up: true }], [{ id: 25, up: true }], [], [], [], [], []];
assert.ok(canMove(state, from, to), 'Red queen + black jack can move onto black king');
assert.equal(move(state, from, to).tableau[1].length, 3);
assert.equal(autoMove(state, from).tableau[1].length, 3, 'One click moves the entire valid stack');
assert.ok(hints(state).some((hint) => hint.from?.pile === 0 && hint.from?.index === 0 && hint.to?.zone === 'tableau' && hint.to.pile === 1), 'Hints include moving a whole stack');
assert.equal(move(state, from, { zone: 'tableau', pile: 2 }), null, 'Only kings fill empty columns');
assert.equal(move(state, from, { zone: 'foundations', pile: 0 }), null, 'Cannot send a stack to a foundation');
assert.equal(move(state, from, from), null);
state.tableau[1][0].id = 12;
assert.equal(move(state, from, to), null, 'Cannot stack the same color');
assert.equal(autoMove(state, from), null, 'No legal destination leaves the game unchanged');
state.tableau[0][0].up = false;
assert.equal(move(state, from, to), null, 'Cannot move hidden cards');
state.tableau = [[{ id: 4, up: false }, { id: 13, up: true }], [], [], [], [], [], []];
state.foundations = [[], [], [], []];
const revealed = move(state, { ...from, index: 1 }, { zone: 'foundations', pile: 1 });
assert.ok(revealed.tableau[0][0].up, 'Removing the top card reveals the next card');
assert.equal(state.tableau[0][0].up, false, 'Undo retains the hidden card');
state.tableau[1] = [{ id: 1, up: true }];
assert.deepEqual(autoMove(state, { ...from, index: 1 }).foundations[1], [13], 'Foundation takes priority over a legal tableau destination');
assert.equal(hints(state)[0].to.zone, 'foundations', 'Hints prioritize foundations');
state.foundations[1] = [13];
state.tableau = [[{ id: 1, up: true }], [{ id: 40, up: true }], [], [], [], [], []];
assert.equal(autoMove(state, { zone: 'foundations', pile: 1, index: 0 }).tableau[0].at(-1).id, 13, 'Foundation card returns to the leftmost legal column');
assert.ok(hints(state).every((hint) => hint.from?.zone !== 'foundations'), 'Hints never send a foundation card back down, preventing up/down loops');
state.waste = [12];
assert.equal(autoMove(state, { zone: 'waste', pile: 0, index: 0 }).tableau[2][0].id, 12, 'Waste king moves to an empty column');
state.tableau = [[{ id: 4, up: false }, { id: 13, up: true }], [], [], [], [], [], []];
state.foundations = [[], [], [], []];
assert.equal(move(state, { ...from, index: 1 }, { zone: 'foundations', pile: 0 }), null, 'Foundations follow suit');
state.waste = [0, 1];
assert.equal(move(state, { zone: 'waste', pile: 0, index: 0 }, { zone: 'foundations', pile: 0 }), null, 'Only the top waste card is playable');

state = { version: 1, moves: 0, stock: [], waste: [], foundations: [[], [], [], []], tableau: [...Array.from({ length: 4 }, (_, s) => Array.from({ length: 13 }, (_, r) => ({ id: s * 13 + 12 - r, up: false }))), [], [], []] };
state.tableau.forEach((pile) => { if (pile.length) pile.at(-1).up = true; });
assert.ok(validState(state));
for (let i = 0; i < 52; i++) {
	const action = foundationMove(state);
	assert.ok(action);
	state = move(state, action.from, action.to);
	assert.ok(validState(state));
}
assert.ok(won(state));
assert.deepEqual(hints(state), [], 'A finished game needs no hint');
assert.equal(draw(state), null);
assert.ok(validState(JSON.parse(JSON.stringify(state))), 'Save round trip');
const nearWin = structuredClone(state);
nearWin.tableau[0] = [{ id: nearWin.foundations[0].pop(), up: true }];
assert.ok(canFinish(nearWin));
assert.ok(won(move(nearWin, from, { zone: 'foundations', pile: 0 })));
assert.ok(canMove(state, { zone: 'foundations', pile: 0, index: 12 }, { zone: 'tableau', pile: 0 }), 'Can return a foundation king to an empty column');
for (const invalid of [null, {}, { ...state, moves: -1 }, { ...state, stock: [0] }, { ...state, tableau: [[null], [], [], [], [], [], []] }, { ...state, foundations: [[0, 2], [], [], []] }]) assert.equal(validState(invalid), false);
assert.equal(rank(51), 13);
assert.equal(suit(51), 3);
const stuck = { version: 1, moves: 0, stock: [], waste: [], foundations: [[], [], [], []], tableau: Array.from({ length: 7 }, () => []) };
assert.deepEqual(hints(stuck), []);
stuck.stock = [4];
assert.deepEqual(hints(stuck), [{ draw: true }], 'Suggest drawing when no card can move');
stuck.stock = [];
stuck.waste = [4];
assert.deepEqual(hints(stuck), [{ draw: true }], 'Suggest recycling an exhausted stock');
stuck.waste = [];
stuck.tableau[0] = [{ id: 12, up: true }];
assert.deepEqual(hints(stuck), [], 'Do not suggest shuffling a whole king column into an empty column');
console.log('Solitaire: deal, legal moves, reveal, recycling, save validation, autocomplete and victory OK');
